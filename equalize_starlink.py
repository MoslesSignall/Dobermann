def _estimate_channel(sss_fft):
    # 1. Divide the received SSS by the known unit-amplitude sequence.
    ref_sss = 1j ** np.array([(SSS_WORD >> (2 * k)) & 3 for k in range(1020)])
    h = np.zeros(1024, dtype=complex)
    usable = np.zeros(1024)
    h[2:1022] = sss_fft[2:1022] * ref_sss.conj()
    usable[2:1022] = 1
    # Weight by the active-tone mask so DC nulls do not pull the estimate down.
    return gaussian_filter1d(h, 8, mode="wrap") / gaussian_filter1d(usable, 8, mode="wrap")


def make_equalizer(sss_fft):
    """Use one SSS to build a channel equalizer for single FFT rows of that frame."""
    sss_fft = np.asarray(sss_fft, dtype=np.complex128)
    if sss_fft.shape != (1024,):
        raise ValueError("Expected 1024 unshifted FFT points for SSS")
    channel = _estimate_channel(sss_fft)

    def equalize(symbol):
        symbol = np.asarray(symbol, dtype=np.complex128)
        if symbol.shape != (1024,):
            raise ValueError("Expected 1024 unshifted FFT points for symbol")
        return symbol / channel

    return equalize


def equalize_starlink(fft_symbols):
    """Input and output rows are [SSS (i=1), i=2, i=3, ...], unshifted FFT order."""
    y = np.asarray(fft_symbols, dtype=np.complex128)
    if y.ndim != 2 or y.shape[1] != 1024 or not 2 <= y.shape[0] <= 301:
        raise ValueError("Expected a (2..301, 1024) array starting at the SSS")
    z = y / _estimate_channel(y[0])

    # 2. Use four pilots per band. The other eight can verify the result.
    pilot_ratio = z[1:, PILOTS] * PILOT_REFERENCE[:len(y) - 1].conj()
    positive = pilot_ratio[:, :8:2].mean(axis=1)
    negative = pilot_ratio[:, 8::2].mean(axis=1)

    # 3. Interpolate phase along signed frequency. Unwrap the difference over time.
    k = np.fft.fftfreq(1024) * 1024
    k_positive = k[PILOTS[:8:2]].mean()
    k_negative = k[PILOTS[8::2]].mean()
    fraction = (k - k_negative) / (k_positive - k_negative)
    phase_gap = np.unwrap(np.angle(positive * negative.conj()))
    phase = np.angle(negative)[:, None] + phase_gap[:, None] * fraction
    z[1:] *= np.exp(-1j * phase)
    return z
